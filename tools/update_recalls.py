#!/usr/bin/env python3
"""Refresh the car seat recall database used by the app.

Downloads NHTSA's public recall flat file (all recalls since 2010), keeps only
child-restraint (car seat) campaigns, and writes data/carseat-recalls.js.

Usage:
    python3 tools/update_recalls.py            # download + rebuild
    python3 tools/update_recalls.py FILE.txt   # rebuild from an already-extracted file

Source: https://static.nhtsa.gov/odi/ffdd/rcl/FLAT_RCL_POST_2010.zip
Field layout: https://static.nhtsa.gov/odi/ffdd/rcl/RCL.txt
"""
import csv
import io
import json
import sys
import tempfile
import urllib.request
import zipfile
from datetime import date
from pathlib import Path

URL = "https://static.nhtsa.gov/odi/ffdd/rcl/FLAT_RCL_POST_2010.zip"
OUT = Path(__file__).resolve().parent.parent / "data" / "carseat-recalls.js"

# 0-based column indexes from RCL.txt
CAMPNO, MAKE, MODEL, YEAR, MFGCAMP, COMP, MFGNAME, BGMAN, ENDMAN, TYPE, POTAFF, ODATE, \
    INFL, MFGTXT, RCDATE, DATEA, RPNO, FMVSS, DESC, CONSEQ, REMEDY, NOTES = range(1, 23)


def fmt(d):
    d = (d or "").strip()
    return f"{d[:4]}-{d[4:6]}-{d[6:8]}" if len(d) == 8 and d.isdigit() else ""


def rows_from(path):
    csv.field_size_limit(sys.maxsize)
    with open(path, encoding="latin-1", newline="") as f:
        for r in csv.reader(f, delimiter="\t", quoting=csv.QUOTE_NONE):
            if len(r) > NOTES and r[TYPE].strip() == "C":
                yield r


def build(path):
    camps = {}
    for r in rows_from(path):
        c = camps.setdefault(r[CAMPNO].strip(), {
            "campaign": r[CAMPNO].strip(),
            "mfrCampaign": r[MFGCAMP].strip(),
            "manufacturer": r[MFGNAME].strip(),
            "component": r[COMP].strip(),
            "reported": fmt(r[RCDATE]),
            "unitsAffected": int(r[POTAFF]) if r[POTAFF].strip().isdigit() else None,
            "summary": r[DESC].strip(),
            "consequence": r[CONSEQ].strip(),
            "remedy": r[REMEDY].strip(),
            "notes": r[NOTES].strip(),
            "products": [],
        })
        p = {
            "make": r[MAKE].strip(),
            "model": r[MODEL].strip(),
            "year": "" if r[YEAR].strip() == "9999" else r[YEAR].strip(),
            "mfgStart": fmt(r[BGMAN]),
            "mfgEnd": fmt(r[ENDMAN]),
        }
        if p not in c["products"]:
            c["products"].append(p)
    data = sorted(camps.values(), key=lambda c: c["reported"], reverse=True)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Generated by tools/update_recalls.py from NHTSA recall data. Do not edit by hand.\n"
        f"window.CARSEAT_RECALLS_UPDATED = {json.dumps(date.today().isoformat())};\n"
        f"window.CARSEAT_RECALLS = {json.dumps(data, separators=(',', ':'))};\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(data)} car seat recall campaigns "
          f"({sum(len(c['products']) for c in data)} seat models) to {OUT}")


def main():
    if len(sys.argv) > 1:
        build(sys.argv[1])
        return
    with tempfile.TemporaryDirectory() as tmp:
        print("Downloading NHTSA recall file (~15 MB)...")
        with urllib.request.urlopen(URL, timeout=300) as resp:
            z = zipfile.ZipFile(io.BytesIO(resp.read()))
        name = next(n for n in z.namelist() if n.lower().endswith(".txt"))
        z.extract(name, tmp)
        build(Path(tmp) / name)


if __name__ == "__main__":
    main()
